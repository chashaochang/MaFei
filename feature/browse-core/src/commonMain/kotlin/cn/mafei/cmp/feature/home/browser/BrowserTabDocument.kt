internal fun MediaBrowserState.pendingTabRequests(): Set<BrowserTabRequest> = buildSet {
    addAll(tabPendingRequests)
    if (loading || refreshing) add(BrowserTabRequest.Library)
    else if (loadingMore) add(BrowserTabRequest.LibraryMore)
    if (detailLoading) add(BrowserTabRequest.Detail)
    else if (detailSectionsLoading) add(BrowserTabRequest.DetailSections)
    if (personLoading || personSectionsLoading) add(BrowserTabRequest.Person)
    if (searchLoading || searchLoadingMore) add(BrowserTabRequest.Search)
}

/** Pending work is retried when a retained Tab returns; completed documents need no request. */
enum class BrowserTabRequest { Library, LibraryMore, Detail, DetailRefresh, DetailSections, Person, Search }

/** Series/season document retained while an episode owns the foreground detail slot. */
data class BrowserSeasonDocument(
    val series: MediaItem,
    val seasons: List<MediaItem>,
    val seasonId: MediaId,
    val season: MediaItem?,
    val episodes: List<MediaItem>,
    val seriesPlayTarget: MediaItem?,
    val seasonPlayTarget: MediaItem?,
)
